"""Result envelopes and markdown reports for the V0.3 lab kit.

Every run writes its machine-readable result as a standard spike envelope
(``spikes._harness.envelope``) under ``<reports>/raw/<day>-<topic>/`` and then
(re)generates ``<reports>/<day>-<topic>.md`` from **every** envelope of that topic
and day, through ``render_report`` + ``write_report``: the report is merged, so
the hand-written sections (Goal, Expected vs actual, Conclusion, ...) survive
every re-run, and the write is atomic.

Topics: ``V0.3-fabric-inventory``, ``V0.3-fabric-watch``, ``V0.3-fabric-restart``,
``V0.3-fabric-soak``, ``V0.3-agent-rss``. Watch and restart runs never overwrite
each other: each run's file name carries its start time.
"""

from __future__ import annotations

from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from datetime import date, datetime
from pathlib import Path
from typing import Any, Final

from spikes._harness.envelope import (
    interpreter,
    load_dir,
    make_envelope,
    raw_dir,
    raw_result_path,
    sanitize_text,
    write_envelope,
)
from spikes._harness.report import (
    cell,
    read_template,
    render_report,
    write_report,
)
from spikes._harness.reps import CaseResult

TASK: Final = "0.3.15"
SPIKE: Final = "—"
TOOL_VERSION: Final = 1

TITLES: Final = {
    "inventory": "V0.3 fabric - node inventory (criterion 1)",
    "watch": "V0.3 fabric - failure detection on a cable pull (criteria 2, 4)",
    "restart": "V0.3 fabric - controller restart (criteria 3, 4)",
    "soak": "V0.3 fabric - 24 h soak (criterion 5, part 1)",
    "rss": "V0.3 fabric - agent memory during the soak (criterion 5, part 2)",
}


def topic(sub: str) -> str:
    return "V0.3-agent-rss" if sub == "rss" else f"V0.3-fabric-{sub}"


@dataclass(frozen=True, slots=True)
class Written:
    json_path: Path
    report_path: Path
    messages: list[str]


def envelope(
    sub: str,
    *,
    link: str | None,
    params: Mapping[str, Any],
    cases: list[CaseResult],
    errors: list[dict[str, Any]] | None = None,
    extra: Mapping[str, Any] | None = None,
    now: datetime | None = None,
    host: Mapping[str, Any] | None = None,
    git: Mapping[str, Any] | None = None,
    host_label: str | None = None,
) -> dict[str, Any]:
    return make_envelope(
        spike="V0.3",
        topic=topic(sub),
        link=link,
        params=params,
        cases=cases,
        errors=errors,
        extra=extra,
        tool={
            "name": "fabric_check" if sub != "rss" else "agent_rss",
            "subcommand": sub,
            "version": TOOL_VERSION,
            "interpreter": interpreter(),
        },
        git=git,
        host=host,
        host_label=host_label,
        now=now,
    )


def write(
    sub: str,
    doc: dict[str, Any],
    *,
    reports_dir: Path,
    day: date,
    suffix: str | None = None,
    extra_md: Callable[[Sequence[dict[str, Any]]], str],
) -> Written:
    """Write ``doc`` and regenerate the topic's report for ``day``.

    Raises ``OSError`` (incl. ``ResultCollisionError``) and ``ReportMergeError`` -
    the caller turns them into one message and exit code 1.
    """
    raw_root = reports_dir / "raw"
    host = str(doc["host"].get("label") or doc["host"]["hostname"])
    json_path = raw_result_path(topic(sub), host, day, suffix=suffix, root=raw_root)
    write_envelope(doc, json_path)
    report_path, messages = render(
        sub, reports_dir=reports_dir, day=day, extra_md=extra_md
    )
    return Written(json_path, report_path, messages)


def render(
    sub: str,
    *,
    reports_dir: Path,
    day: date,
    extra_md: Callable[[Sequence[dict[str, Any]]], str],
) -> tuple[Path, list[str]]:
    """(Re)generate ``<reports>/<day>-<topic>.md`` from every envelope of that day."""
    raw_root = reports_dir / "raw"
    docs, skipped = load_dir(raw_dir(topic(sub), day, raw_root))
    docs = [d for d in docs if d.get("topic") == topic(sub)]
    extra = extra_md(docs)
    if skipped:
        extra += "\n\nResult files skipped as invalid:\n" + "".join(
            f"- {cell(s)}\n" for s in skipped
        )
    text = render_report(
        read_template(),
        docs,
        topic=topic(sub),
        title=TITLES[sub],
        day=day.isoformat(),
        task=TASK,
        spike=SPIKE,
        author="generated by lab/agent_rss.py"
        if sub == "rss"
        else "generated by lab/fabric_check.py",
        extra_results=sanitize_text(extra),
    )
    report_path = reports_dir / f"{day.isoformat()}-{topic(sub)}.md"
    result = write_report(report_path, text)
    return report_path, result.messages()


# -------------------------------------------------------------- formatting
def fmt_s(value: object) -> str:
    return (
        f"{value:.2f}"
        if isinstance(value, int | float) and not isinstance(value, bool)
        else "—"
    )


def yes_no(value: object) -> str:
    if value is True:
        return "yes"
    if value is False:
        return "no"
    return "unknown"


def _cases(doc: Mapping[str, Any]) -> list[Mapping[str, Any]]:
    cases = doc.get("cases")
    if not isinstance(cases, Mapping):
        return []
    return [c for _, c in sorted(cases.items()) if isinstance(c, Mapping)]


def _samples(case: Mapping[str, Any]) -> list[Mapping[str, Any]]:
    samples = case.get("samples")
    return (
        [s for s in samples if isinstance(s, Mapping)]
        if isinstance(samples, list)
        else []
    )


def watch_md(docs: Sequence[dict[str, Any]]) -> str:
    lines = [
        "### Per repetition (cable pull, criterion 2: OFFLINE <= 8 s, ONLINE <= 10 s, no "
        "agent restart; agent stop/start, criterion 4: back with the same node_id)",
        "",
        "| Run | Node | Rep | offline s | online s | Session end reason | Epoch before -> after "
        "| Agent process restarted | Within bounds |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for doc in docs:
        run = cell(doc.get("_source", doc.get("timestamp_utc", "")))
        for case in _cases(doc):
            label = cell(case.get("label", ""))
            for s in _samples(case):
                bounds = [
                    s.get(f"{k}_within_bound")
                    for k in ("offline", "online")
                    if f"{k}_s" in s
                ]
                if all(b is None for b in bounds):
                    ok = "n/a"  # agent stop/start run (criterion 4): no timing bound
                else:
                    ok = "yes" if all(b is True for b in bounds) else "NO"
                lines.append(
                    f"| {run} | {label} | {int(s.get('rep', 0)) + 1} | {fmt_s(s.get('offline_s'))} "
                    f"| {fmt_s(s.get('online_s'))} | {cell(s.get('end_reason') or '—')} "
                    f"| {s.get('epoch_before', '—')} -> {s.get('epoch_after', '—')} "
                    f"| {yes_no(s.get('restarted'))} | {ok} |"
                )
    lines += [
        "",
        "How to read it: *latency* = from the operator's Enter to the first poll answer "
        "showing the state (upper bound; poll interval in the JSON `params`). "
        "*Session end reason*: `stream_lost` = the OS reset/closed the TCP connection, so "
        "the controller saw the loss at once (SUSPECT at once, OFFLINE still at the lease "
        "edge); `lease_expired` = nothing arrived and the 6 s lease ran out (a silent cable "
        "pull); `agent_closed` = the agent said goodbye (a clean stop, criterion 4 runs). "
        "*Agent process restarted* comes from the per-process resource `sequence` (it "
        "restarts at 1 only in a new process); `session_epoch` is bumped on every "
        "reconnect and is shown only for reference. Loopback prediction "
        "(V0.3 G6-B, shipped timings): blackhole -> OFFLINE ~6.0 s, restore -> ONLINE ~0.3 s.",
    ]
    return "\n".join(lines)


def restart_md(docs: Sequence[dict[str, Any]]) -> str:
    lines = [
        "### Per repetition (criterion 3: every node connected again <= 15 s; "
        "criterion 4: same node_id)",
        "",
        "| Run | Rep | Controller outage s | All reconnected after s | Nodes back | node_id kept "
        "| Agent process restarted | Within bound |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for doc in docs:
        run = cell(doc.get("_source", doc.get("timestamp_utc", "")))
        for case in _cases(doc):
            if case.get("attrs", {}).get("kind") != "all":
                continue
            for s in _samples(case):
                raw_nodes = s.get("nodes")
                nodes: Mapping[str, Any] = (
                    raw_nodes if isinstance(raw_nodes, Mapping) else {}
                )
                back = sum(
                    1
                    for d in nodes.values()
                    if isinstance(d, Mapping) and d.get("reconnect_s") is not None
                )
                kept = [
                    d.get("node_id_kept")
                    for d in nodes.values()
                    if isinstance(d, Mapping)
                ]
                rest = [
                    f"{d.get('hostname')}"
                    for d in nodes.values()
                    if isinstance(d, Mapping) and d.get("restarted") is True
                ]
                lines.append(
                    f"| {run} | {int(s.get('rep', 0)) + 1} | {fmt_s(s.get('outage_s'))} "
                    f"| {fmt_s(s.get('reconnect_all_s'))} | {back}/{len(nodes)} "
                    f"| {'yes' if kept and all(k is True for k in kept) else 'NO'} "
                    f"| {cell(', '.join(rest)) if rest else 'none'} "
                    f"| {'yes' if s.get('reconnect_all_within_bound') is True else 'NO'} |"
                )
    lines += [
        "",
        "*All reconnected after* is measured from the first `/healthz` answer of the new "
        "controller process, so the time a human took to restart it is excluded (it is the "
        "outage column). Loopback prediction (V0.3 G6-B): SIGKILL + restart -> all agents "
        "ONLINE ~2.4 s.",
    ]
    return "\n".join(lines)


def soak_md(docs: Sequence[dict[str, Any]]) -> str:
    lines = [
        "The generic table above is empty on purpose: a soak is one long observation, "
        "not repetitions.",
        "",
        "| Host (controller) | Observed h / target | Finished | OFFLINE events | by reason "
        "| SUSPECT events | Session ends by reason | Controller outages | Tool gaps |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for doc in docs:
        summary = doc.get("extra", {}).get("summary", {})
        if not isinstance(summary, Mapping):
            continue
        lines.append(
            f"| {cell(doc.get('host', {}).get('label', ''))} "
            f"| {summary.get('observed_h')} / {summary.get('target_h')} "
            f"| {yes_no(summary.get('done'))} | {summary.get('offline_events')} "
            f"| {cell(_pairs(summary.get('offline_by_reason')))} | {summary.get('suspect_events')} "
            f"| {cell(_pairs(summary.get('session_ends_by_reason')))} "
            f"| {summary.get('outages')} ({fmt_s(summary.get('outage_s'))} s) "
            f"| {summary.get('gaps')} |"
        )
        transitions = doc.get("extra", {}).get("offline_transitions") or []
        if transitions:
            lines += [
                "",
                "OFFLINE transitions (every one is a false OFFLINE unless the team "
                "caused it on purpose):",
                "",
            ]
            lines += [
                f"- {cell(t.get('at'))} {cell(t.get('hostname'))} ({cell(t.get('node_id'))}): "
                f"reason `{cell(t.get('reason'))}`"
                + (" (noticed after a tool gap)" if t.get("during_gap") else "")
                for t in transitions
            ]
    lines += [
        "",
        "Criterion 5 part 1 asks for **zero false OFFLINE events** over 24 h on Ethernet. "
        "A tool gap (the soak tool itself was not running) is not observed time; the observed "
        "hours column says how much really was.",
    ]
    return "\n".join(lines)


def _pairs(value: object) -> str:
    if not isinstance(value, Mapping) or not value:
        return "none"
    return ", ".join(f"{k}: {v}" for k, v in value.items())


def inventory_md(docs: Sequence[dict[str, Any]]) -> str:
    from _fabric.inventory import COLUMNS, row

    lines = []
    for doc in docs[-1:]:  # the newest inventory run of the day
        details = doc.get("extra", {}).get("nodes") or []
        lines += [
            f"### Nodes as the controller reported them ({cell(doc.get('timestamp_utc'))})",
            "",
            "| " + " | ".join(COLUMNS) + " |",
            "|" + "---|" * len(COLUMNS),
        ]
        for detail in details:
            if isinstance(detail, dict):
                r = row(detail)
                lines.append("| " + " | ".join(cell(r[c]) for c in COLUMNS) + " |")
        for note in doc.get("extra", {}).get("notes") or []:
            lines.append(f"\n- {cell(note)}")
    lines += [
        "",
        "Criterion 1 (all 4 laptops appear with hardware matching `docs/LAB.md` §1) is a "
        "**human comparison**: this tool does not decide it. Compare each row with the "
        "laptop's column in docs/LAB.md §1 and its `lab/reports/inventory/<host>.json`, and "
        "write the outcome under *Expected vs actual*.",
    ]
    return "\n".join(lines)


def rss_md(docs: Sequence[dict[str, Any]]) -> str:
    lines = [
        "| Laptop | Agent pid(s) | Samples | Baseline MiB | End MiB | Max MiB | Growth % "
        "(end vs baseline) | Max growth % | Agent restarts seen | Growth < 10 % |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for doc in docs:
        s = doc.get("extra", {}).get("summary", {})
        if not isinstance(s, Mapping):
            continue
        growth = s.get("growth_pct")
        lines.append(
            f"| {cell(doc.get('host', {}).get('label', ''))} "
            f"| {cell(', '.join(str(p) for p in s.get('pids') or []))} "
            f"| {s.get('samples')} | {fmt_s(s.get('baseline_mib'))} | {fmt_s(s.get('end_mib'))} "
            f"| {fmt_s(s.get('max_mib'))} | {fmt_s(growth)} | {fmt_s(s.get('max_growth_pct'))} "
            f"| {s.get('restarts')} "
            f"| {yes_no(growth < 10.0) if isinstance(growth, int | float) else 'unknown'} |"
        )
    lines += [
        "",
        "Baseline = the first sample taken at least `warmup_min` minutes after sampling began "
        "(the agent's import-time and first-connection allocations are not a leak). Growth is "
        "computed over one agent process; if the agent restarted during the soak the column "
        "*Agent restarts seen* is non-zero and the soak's no-restart premise is broken.",
    ]
    return "\n".join(lines)
