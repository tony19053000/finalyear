"""Declarative base, constraint naming convention and shared column helpers.

**Naming convention.** Every index/constraint gets a deterministic name. Without it
PostgreSQL invents names (``nodes_pkey``, ``nodes_node_id_fkey``) that Alembic cannot
reproduce, so autogenerated ``drop_constraint`` calls in downgrades would need
hand-written names. Changing the convention later would rename constraints in a
migration, so treat it as frozen.

**Time.** All timestamps are ``timestamptz`` (``datetime`` annotations map to
``DateTime(timezone=True)``). Values are set by the database (``now()``) and sessions
run with ``timezone=UTC`` (see :mod:`.engine`), so they come back as aware UTC
datetimes.

**IDs.** Primary keys of fabric entities are the application-generated prefixed
ULID strings from :mod:`meshforge.common.ids` (``job_01J...``). They are created in
Python *before* the insert, so the ID can appear in logs and idempotency records
before the row exists; the database never generates them.
"""

from __future__ import annotations

import datetime as dt
from typing import Final

from sqlalchemy import DateTime, MetaData, String, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

__all__ = [
    "ID_MAX_LENGTH",
    "NAMING_CONVENTION",
    "Base",
    "TimestampMixin",
    "id_column",
]

NAMING_CONVENTION: Final[dict[str, str]] = {
    "ix": "ix_%(column_0_N_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

# "<prefix>_<26-char ULID>"; prefixes are short (``job``, ``node``, ``chunk``...).
# 40 leaves room for longer future prefixes without a type change.
ID_MAX_LENGTH: Final = 40


class Base(DeclarativeBase):
    """Base class of every controller model; ``Base.metadata`` is Alembic's target."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map = {  # noqa: RUF012 - SQLAlchemy reads this class attribute
        dt.datetime: DateTime(timezone=True),
    }


def id_column(*, primary_key: bool = False) -> Mapped[str]:
    """A prefixed-ULID column (``String(ID_MAX_LENGTH)``), e.g. ``id_column(primary_key=True)``.

    Use for primary keys and for foreign keys' local column type.
    """
    return mapped_column(String(ID_MAX_LENGTH), primary_key=primary_key, nullable=False)


class TimestampMixin:
    """``created_at`` / ``updated_at`` (timestamptz, set by the database)."""

    created_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[dt.datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )
