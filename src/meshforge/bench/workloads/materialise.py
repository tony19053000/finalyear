"""Turn ``(family, params, seed)`` into a normal job folder (V0.9 G2, D214).

A benchmark job is an ordinary MeshForge job - submitted, planned, staged and
executed through the same paths as a user's (ARCHITECTURE §17) - so the
library's output is just a project folder::

    compute.yaml              the manifest (entrypoint argv, never a shell)
    run_workload.py           3-line entrypoint -> bench_kernels.runner.main()
    workload_params.json      {"family", "params", "seed"} (canonical JSON)
    requirements.txt          numpy==<pinned>, only for families that use numpy
    bench_kernels/            __init__, _support, runner + the family's kernel module

The run writes ``results/workload.json`` (:mod:`.kernels.runner`), the job's
declared output. ``env.base`` is ``python-cpu`` (CPU / memory families) or
``cuda-pytorch`` with ``resources.gpu: required`` (GPU / ML families);
``resources.ram_gb`` / ``vram_gb`` come from the family's estimate so the
planner can refuse a node that is too small.

**Byte-identical.** The same ``(family, params, seed)`` and the same MeshForge
version give the same files byte for byte - and so the same bundle digest
(the blob store then holds one copy, and V0.5's "resubmit uploads nothing"
applies): fixed file set, sorted JSON, LF line endings (kernel sources are
normalised in case a Windows checkout turned them into CRLF), no timestamps.
The folder holds no MeshForge import: the job environment has none.
"""

from __future__ import annotations

import contextlib
import hashlib
import json
import os
import shutil
import tempfile
import uuid
from collections.abc import Mapping
from dataclasses import dataclass
from importlib import resources
from pathlib import Path
from typing import Any, ClassVar, Final

import yaml

from meshforge.common.errors import FailureType, MeshForgeError
from meshforge.common.logging import get_logger
from meshforge.common.manifest import MANIFEST_FILE_NAME, Manifest, load_manifest

from . import kernels
from .base import Family, Params, get_family, round_up_gb
from .kernels._support import canonical_json
from .kernels.runner import KERNEL_MODULES, PARAMS_FILE, RESULT_FILE

__all__ = [
    "ENTRYPOINT",
    "JOB_TIMEOUT",
    "KERNEL_PACKAGE",
    "NUMPY_REQUIREMENT",
    "BuiltJob",
    "MaterialiseError",
    "build_job",
    "job_files",
]

log = get_logger(__name__)

KERNEL_PACKAGE: Final = "bench_kernels"
"""The kernels' package name inside a job folder."""

ENTRYPOINT: Final = ("python", "run_workload.py")

# Bumps in lockstep with uv.lock (a unit test fails while the two differ). A bump
# changes requirements.txt, so every numpy family's job tree - and its bundle
# digest - changes: that is a **dataset-version event** (D225). Runs before and
# after measured different numpy builds; record the bump where G5's dataset
# versioning records library changes, never mix the two silently.
NUMPY_REQUIREMENT: Final = "numpy==2.5.3"
"""The numpy every CPU benchmark job installs: pinned (a dataset must not mix
numpy builds silently) and equal to ``uv.lock`` (a unit test holds the two
together). Envs are cached by hash (V0.5 D86), so it is downloaded once per
node, not per run. Changing it changes the job tree digests (see the comment
above)."""

JOB_TIMEOUT: Final = "15m"
"""A run is 5 s - 3 min on the mid laptop; 15 min leaves room for a laptop 3x
slower plus data generation and the self-check, and still stops a hung run."""

RUN_WORKLOAD = f'''"""MeshForge benchmark job (generated by meshforge.bench; do not edit)."""

import sys

from {KERNEL_PACKAGE}.runner import main

if __name__ == "__main__":
    sys.exit(main())
'''


class MaterialiseError(MeshForgeError, ValueError):
    """The destination cannot take a job folder (exists and is not empty)."""

    default_failure_type: ClassVar[FailureType] = FailureType.INVALID_INPUT


@dataclass(frozen=True)
class BuiltJob:
    """A written job folder. ``content_digest`` = sha256 over every
    ``(relative path, bytes)`` in path order: equal digests mean byte-identical
    folders."""

    path: Path
    family: str
    params: dict[str, Any]
    seed: int
    manifest: Manifest
    files: tuple[str, ...]
    content_digest: str


def _kernel_source(module: str) -> bytes:
    data = resources.files(kernels).joinpath(f"{module}.py").read_bytes()
    return data.replace(b"\r\n", b"\n")


def _manifest_document(
    family: Family[Any], params: Params, request_digest: str
) -> dict[str, Any]:
    resources_doc: dict[str, Any] = {
        "gpu": "required" if family.gpu else "none",
        "ram_gb": round_up_gb(family.ram_gb(params)),
    }
    vram = family.vram_gb(params)
    if vram is not None:
        resources_doc["vram_gb"] = vram
    env: dict[str, Any] = {"base": family.env_base}
    if family.needs_numpy:
        env["requirements"] = "requirements.txt"
    return {
        "name": f"bench-{family.name}-{request_digest[:10]}",
        "entrypoint": list(ENTRYPOINT),
        "env": env,
        "resources": resources_doc,
        "outputs": [RESULT_FILE.split("/", 1)[0] + "/"],
        "limits": {"timeout": JOB_TIMEOUT, "network": "none"},
    }


def job_files(
    family: str | Family[Any], params: Params | Mapping[str, Any], seed: int
) -> dict[str, bytes]:
    """The folder's files (relative POSIX path -> bytes), without writing them.

    Raises :class:`~.base.ParamsError` (bad params, outside the 5 s - 3 min
    window, seed out of range) and :class:`~.base.UnknownFamilyError`.
    """
    fam = get_family(family) if isinstance(family, str) else family
    fam.check_seed(seed)
    checked = fam.parse_params(params)
    request = {"family": fam.name, "params": fam.params_dict(checked), "seed": seed}
    request_json = canonical_json(request)
    request_digest = hashlib.sha256(request_json.encode()).hexdigest()

    manifest_text = (
        "# MeshForge benchmark job (generated by meshforge.bench; do not edit).\n"
        f"# {fam.name} seed {seed}: see {PARAMS_FILE} and docs/BENCHMARKS.md.\n"
        + yaml.safe_dump(
            _manifest_document(fam, checked, request_digest),
            sort_keys=False,
            default_flow_style=False,
            allow_unicode=False,
        )
    )
    module = KERNEL_MODULES[fam.name]
    files: dict[str, bytes] = {
        MANIFEST_FILE_NAME: manifest_text.encode(),
        "run_workload.py": RUN_WORKLOAD.encode(),
        PARAMS_FILE: (request_json + "\n").encode(),
    }
    if fam.needs_numpy:
        files["requirements.txt"] = (NUMPY_REQUIREMENT + "\n").encode()
    for name in ("__init__", "_support", "runner", module):
        files[f"{KERNEL_PACKAGE}/{name}.py"] = _kernel_source(name)
    return dict(sorted(files.items()))


def _content_digest(files: Mapping[str, bytes]) -> str:
    hasher = hashlib.sha256()
    for name in sorted(files):
        for part in (name.encode(), files[name]):
            hasher.update(len(part).to_bytes(8, "little"))
            hasher.update(part)
    return "sha256:" + hasher.hexdigest()


def _refuse_busy(dest: Path) -> None:
    if dest.exists() and (not dest.is_dir() or any(dest.iterdir())):
        raise MaterialiseError(
            f"{dest} already exists and is not an empty folder",
            details={"path": str(dest)},
        )


def _publish(staging: Path, dest: Path) -> None:
    """Rename ``staging`` to ``dest``; ``dest`` may be absent or an empty folder.

    POSIX renames onto an empty folder atomically. Windows refuses to rename onto
    an existing folder, so the caller's empty ``dest`` is first renamed *aside*
    (never deleted) and put back if the final rename fails - a failed build never
    loses the folder the caller made (tester r2 D7). The aside name carries a
    ``uuid4`` (D225): pid + ``id()`` could repeat across processes or after a
    crash left an old aside behind, and a clashing rename would refuse the build.

    If another builder fills ``dest`` between our aside step and our final
    rename, the restore fails (``dest`` exists): we lost the race, the caller's
    folder is now the winner's, and the aside is our own empty folder - removed,
    never left behind (tester r1 TR1-A1).
    """
    with contextlib.suppress(OSError):
        os.rename(staging, dest)
    if not staging.exists():
        return
    busy = MaterialiseError(
        f"{dest} already exists and is not an empty folder",
        details={"path": str(dest)},
    )
    if not dest.is_dir() or any(dest.iterdir()):
        raise busy
    aside = dest.with_name(f".{dest.name}.aside-{uuid.uuid4().hex}")
    try:
        os.rename(dest, aside)
    except OSError:
        raise busy from None
    try:
        os.rename(staging, dest)
    except OSError:
        try:
            os.rename(aside, dest)  # restore the caller's empty folder
        except OSError:
            _drop_aside(aside, dest)
        raise busy from None
    with contextlib.suppress(OSError):
        aside.rmdir()


def _drop_aside(aside: Path, dest: Path) -> None:
    """Remove our empty aside folder after a lost race (``rmdir`` only: it
    refuses a non-empty folder, so nothing can be lost)."""
    try:
        aside.rmdir()
    except OSError as exc:
        log.warning(
            "bench.materialise.aside_left",
            path=str(aside),
            dest=str(dest),
            error_type=type(exc).__name__,
        )
        return
    log.info("bench.materialise.aside_removed", path=str(aside), dest=str(dest))


def build_job(
    family: str | Family[Any],
    params: Params | Mapping[str, Any],
    seed: int,
    dest: Path,
) -> BuiltJob:
    """Write the job folder for one run into ``dest`` (new, or an empty folder),
    atomically: ``dest`` holds either nothing new or the complete folder.

    The written manifest is read back with the fabric's own loader
    (:func:`~meshforge.common.manifest.load_manifest`), so a folder this returns
    is one ``compute run`` accepts.
    """
    files = job_files(family, params, seed)
    _refuse_busy(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    # Atomic (tester r1 D7): the folder is written and validated in a private
    # sibling, then renamed into place in one step - nobody (a racing builder, a
    # `compute run` started too early) ever sees a half-written folder.
    staging = Path(tempfile.mkdtemp(prefix=f".{dest.name}.building-", dir=dest.parent))
    try:
        for name, data in files.items():
            target = staging.joinpath(*name.split("/"))
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        manifest = load_manifest(staging)
        _publish(staging, dest)
    finally:
        if staging.exists():
            shutil.rmtree(staging, ignore_errors=True)
    request: dict[str, Any] = json.loads(files[PARAMS_FILE])
    return BuiltJob(
        path=dest,
        family=request["family"],
        params=request["params"],
        seed=request["seed"],
        manifest=manifest,
        files=tuple(files),
        content_digest=_content_digest(files),
    )
