PARAMS_FILE: Final = "workload_params.json"
EXIT_BAD_PARAMS: Final = 2
EXIT_CHECK_FAILED: Final = 4

IMAGE_DIR: Final = "data/img"
FILE_DIR: Final = "data/files"
TABLE_FILE: Final = "data/table.csv"
_PPM_MAGIC: Final = b"P6"
_MC_BATCH: Final = 1 << 20
_MC_CHECK_BATCH: Final = 1 << 16
_MC_SIGMAS: Final = 7.0
_HASH_PIECE: Final = 64 * 1024
_IMAGE_BATCH: Final = 64


def stream_bytes(seed: int, label: str, index: int, size: int) -> bytes:
    """``size`` deterministic bytes for (seed, label, index) - SHAKE-256."""
    key = f"meshforge.split|{label}|{seed}|{index}".encode()
    return hashlib.shake_256(key).digest(size)


def _int(params: Mapping[str, Any], name: str, low: int, high: int) -> int:
    value = params.get(name)
    if isinstance(value, bool) or not isinstance(value, int):
        raise KernelParamsError(f"{name}: expected an integer, got {value!r}")
    if not low <= value <= high:
        raise KernelParamsError(f"{name}: must be {low}..{high}, got {value}")
    return value


@dataclass(frozen=True)
class SplitKernel:
    """One family's job side: ``run`` -> output files; ``check`` -> a problem
    or None; ``check_params`` raises :class:`KernelParamsError`."""

    run: Callable[[Mapping[str, Any], int, bytes], dict[str, bytes]]
    check: Callable[[Mapping[str, Any], int, bytes, Mapping[str, bytes]], str | None]
    check_params: Callable[[Mapping[str, Any]], None]
    items_label: str
    """What one item is (``image``, ``file``, ``point set``, ``row``)."""


def _json_items(data: bytes) -> list[Any]:
    items = json.loads(data.decode("utf-8"))
    if not isinstance(items, list) or not items:
        raise KernelParamsError("the items file is not a non-empty JSON list")
    return items


def _paths(data: bytes, folder: str) -> list[str]:
    items = _json_items(data)
    prefix = folder + "/"
    for item in items:
        if not isinstance(item, str) or not item.startswith(prefix) or ".." in item:
            raise KernelParamsError(f"item {item!r} is not a file of {folder}/")
    return [str(i) for i in items]


# ------------------------------------------------------------ image_classify


def image_name(index: int) -> str:
    return f"{IMAGE_DIR}/{index:05d}.ppm"


def image_bytes(seed: int, index: int, size: int) -> bytes:
    header = f"P6\n{size} {size}\n255\n".encode("ascii")
    return header + stream_bytes(seed, "img", index, size * size * 3)


def _decode_ppm(np: Any, data: bytes, size: int) -> Any:
    header = f"P6\n{size} {size}\n255\n".encode("ascii")
    if not data.startswith(header) or len(data) != len(header) + size * size * 3:
        raise KernelParamsError("an image is not a P6 picture of the expected size")
    pixels = np.frombuffer(data, dtype=np.uint8, offset=len(header))
    return pixels.reshape(size, size, 3).astype(np.int64)


def cnn_weights(np: Any, width: int) -> tuple[Any, Any, Any, Any, Any]:
    """The fixed model (built in code): small integer weights in [-8, 7]."""
    raw = hashlib.shake_256(f"meshforge.image_classify.v1|{width}".encode()).digest(
        27 * width + width + 9 * width * width + width + width * 10
    )
    values = np.frombuffer(raw, dtype=np.uint8).astype(np.int64) % 16 - 8
    at = 0

    def take(n: int) -> Any:
        nonlocal at
        part = values[at : at + n]
        at += n
        return part

    w1 = take(27 * width).reshape(27, width)
    b1 = take(width)
    w2 = take(9 * width * width).reshape(9 * width, width)
    b2 = take(width)
    w3 = take(width * 10).reshape(width, 10)
    return w1, b1, w2, b2, w3


def _im2col(np: Any, x: Any) -> Any:
    """(B, s, s, C) -> (B, s, s, 9C): the 3x3 'same' neighbourhoods, offsets
    (dy, dx) major, channel minor."""
    s = x.shape[1]
    pad = np.pad(x, ((0, 0), (1, 1), (1, 1), (0, 0)))
    return np.concatenate(
        [pad[:, dy : dy + s, dx : dx + s, :] for dy in range(3) for dx in range(3)],
        axis=3,
    )


def _pool(x: Any) -> Any:
    return (
        x[:, 0::2, 0::2] + x[:, 1::2, 0::2] + x[:, 0::2, 1::2] + x[:, 1::2, 1::2]
    ) >> 2


def classify_batch(np: Any, images: Any, width: int) -> tuple[list[int], list[int]]:
    """(labels, scores) of a (B, s, s, 3) int64 batch - im2col + matmul."""
    w1, b1, w2, b2, w3 = cnn_weights(np, width)
    batch, s = images.shape[0], images.shape[1]
    h = _im2col(np, images).reshape(-1, 27) @ w1 + b1
    h = (np.maximum(h, 0) >> 4).reshape(batch, s, s, width)
    p = _pool(h)
    half = p.shape[1]
    h2 = _im2col(np, p).reshape(-1, 9 * width) @ w2 + b2
    h2 = (np.maximum(h2, 0) >> 6).reshape(batch, half, half, width)
    logits = h2.sum(axis=(1, 2)) @ w3
    return [int(v) for v in logits.argmax(axis=1)], [int(v) for v in logits.max(axis=1)]


def classify_reference(np: Any, image: Any, width: int) -> tuple[int, int]:
    """One (s, s, 3) image through direct convolution loops (no im2col, no
    matrix product) - the self-check's independent path."""
    w1, b1, w2, b2, w3 = cnn_weights(np, width)

    def conv(x: Any, w: Any, b: Any, channels: int) -> Any:
        s = x.shape[0]
        pad = np.pad(x, ((1, 1), (1, 1), (0, 0)))
        out = np.zeros((s, s, w.shape[1]), dtype=np.int64)
        for dy in range(3):
            for dx in range(3):
                for c in range(channels):
                    row = (dy * 3 + dx) * channels + c
                    out += pad[dy : dy + s, dx : dx + s, c][:, :, None] * w[row]
        return out + b

    h = np.maximum(conv(image, w1, b1, 3), 0) >> 4
    p = _pool(h[None])[0]
    h2 = np.maximum(conv(p, w2, b2, width), 0) >> 6
    g = h2.sum(axis=(0, 1))
    logits = [
        int(sum(int(g[k]) * int(w3[k, j]) for k in range(width))) for j in range(10)
    ]
    best = max(logits)
    return logits.index(best), best


def _image_params(params: Mapping[str, Any]) -> tuple[int, int, int]:
    images = _int(params, "images", 1, 20_000)
    size = _int(params, "size", 16, 32)
    if size not in (16, 32):
        raise KernelParamsError(f"size: expected one of [16, 32], got {size}")
    width = _int(params, "width", 4, 32)
    return images, size, width


def _image_run(params: Mapping[str, Any], seed: int, items: bytes) -> dict[str, bytes]:
    np = require_numpy()
    _images, size, width = _image_params(params)
    paths = _paths(items, IMAGE_DIR)
    lines: list[str] = []
    for start in range(0, len(paths), _IMAGE_BATCH):
        group = paths[start : start + _IMAGE_BATCH]
        batch = np.stack([_decode_ppm(np, Path(p).read_bytes(), size) for p in group])
        labels, scores = classify_batch(np, batch, width)
        lines.extend(
            f"{p},{label},{score}\n"
            for p, label, score in zip(group, labels, scores, strict=True)
        )
    return {"predictions.csv": "".join(lines).encode("utf-8")}


def _image_check(
    params: Mapping[str, Any], seed: int, items: bytes, out: Mapping[str, bytes]
) -> str | None:
    np = require_numpy()
    _images, size, width = _image_params(params)
    paths = _paths(items, IMAGE_DIR)
    lines = out["predictions.csv"].decode("utf-8").splitlines()
    if len(lines) != len(paths):
        return f"{len(lines)} predictions for {len(paths)} images"
    for index in sorted({0, len(paths) - 1}):
        image = _decode_ppm(np, Path(paths[index]).read_bytes(), size)
        label, score = classify_reference(np, image, width)
        if lines[index] != f"{paths[index]},{label},{score}":
            return f"image {paths[index]}: the direct convolution disagrees"
    return None


# ------------------------------------------------------------ hash_files


def file_name(index: int) -> str:
    return f"{FILE_DIR}/{index:05d}.bin"


def file_bytes(seed: int, index: int, size: int) -> bytes:
    """Half random (incompressible), half a repeated 64-byte pattern."""
    half = size // 2
    pattern = stream_bytes(seed, "pattern", index, 64)
    rest = (pattern * (size // 64 + 2))[: size - half]
    return stream_bytes(seed, "file", index, half) + rest


def _chain(data: bytes, rounds: int) -> bytes:
    digest = hashlib.sha256(data).digest()
    for _ in range(rounds - 1):
        hasher = hashlib.sha256(digest)
        hasher.update(data)
        digest = hasher.digest()
    return digest


def _chain_pieces(data: bytes, rounds: int) -> bytes:
    """:func:`_chain` fed in 64 KiB pieces (the check's second path)."""
    view = memoryview(data)
    hasher = hashlib.sha256()
    for at in range(0, len(data), _HASH_PIECE):
        hasher.update(view[at : at + _HASH_PIECE])
    digest = hasher.digest()
    for _ in range(rounds - 1):
        hasher = hashlib.sha256()
        hasher.update(digest)
        for at in range(0, len(data), _HASH_PIECE):
            hasher.update(view[at : at + _HASH_PIECE])
        digest = hasher.digest()
    return digest


def _hash_params(params: Mapping[str, Any]) -> tuple[int, int, int]:
    return (
        _int(params, "files", 1, 4096),
        _int(params, "size_kb", 1, 1024),
        _int(params, "rounds", 1, 256),
    )


def _hash_run(params: Mapping[str, Any], seed: int, items: bytes) -> dict[str, bytes]:
    _files, _size_kb, rounds = _hash_params(params)
    lines: list[str] = []
    for path in _paths(items, FILE_DIR):
        data = Path(path).read_bytes()
        zipped = len(zlib.compress(data, 6))
        lines.append(f"{path},{len(data)},{_chain(data, rounds).hex()},{zipped}\n")
    return {"hashes.csv": "".join(lines).encode("utf-8")}


def _hash_check(
    params: Mapping[str, Any], seed: int, items: bytes, out: Mapping[str, bytes]
) -> str | None:
    _files, size_kb, rounds = _hash_params(params)
    paths = _paths(items, FILE_DIR)
    lines = out["hashes.csv"].decode("utf-8").splitlines()
    if len(lines) != len(paths):
        return f"{len(lines)} hashes for {len(paths)} files"
    data = Path(paths[0]).read_bytes()
    if len(data) != size_kb * 1024:
        return f"file {paths[0]} has {len(data)} bytes, expected {size_kb * 1024}"
    if zlib.decompress(zlib.compress(data, 6)) != data:
        return "zlib round trip changed the data"
    fields = lines[0].split(",")
    if fields[:3] != [paths[0], str(len(data)), _chain_pieces(data, rounds).hex()]:
        return f"file {paths[0]}: the hash in pieces disagrees"
    return None


# ------------------------------------------------------------ montecarlo_range


def inside_count(np: Any, seed: int, item: int, samples: int, batch: int) -> int:
    """Points of ``samples`` uniform (x, y) in the unit square that fall in
    the quarter circle - item ``item``'s own PCG64 stream."""
    rng = np.random.Generator(np.random.PCG64(np.random.SeedSequence([seed, item])))
    left, inside = samples, 0
    while left > 0:
        n = min(batch, left)
        xy = rng.random((n, 2))
        inside += int(np.count_nonzero((xy * xy).sum(axis=1) <= 1.0))
        left -= n
    return inside


def _mc_params(params: Mapping[str, Any]) -> tuple[int, int]:
    return _int(params, "items", 1, 100_000), _int(params, "samples", 1, 10_000_000)


def _mc_items(items: bytes) -> list[int]:
    out: list[int] = []
    for item in _json_items(items):
        if isinstance(item, bool) or not isinstance(item, int) or item < 0:
            raise KernelParamsError(f"item {item!r} is not a non-negative integer")
        out.append(item)
    return out


def _mc_run(params: Mapping[str, Any], seed: int, items: bytes) -> dict[str, bytes]:
    np = require_numpy()
    _n, samples = _mc_params(params)
    rows = [
        [i, inside_count(np, seed, i, samples, _MC_BATCH)] for i in _mc_items(items)
    ]
    text = json.dumps(rows, separators=(",", ":")) + "\n"
    return {"results.json": text.encode("utf-8")}


def _mc_check(
    params: Mapping[str, Any], seed: int, items: bytes, out: Mapping[str, bytes]
) -> str | None:
    np = require_numpy()
    _n, samples = _mc_params(params)
    wanted = _mc_items(items)
    rows = json.loads(out["results.json"])
    if [r[0] for r in rows] != wanted:
        return "results are not one row per item in item order"
    p = math.pi / 4
    spread = _MC_SIGMAS * math.sqrt(samples * p * (1 - p))
    for item, inside in rows:
        if abs(inside - samples * p) > spread:
            return f"item {item}: {inside}/{samples} is {_MC_SIGMAS:g} sigma off pi/4"
    again = inside_count(np, seed, wanted[0], samples, _MC_CHECK_BATCH)
    if again != rows[0][1]:
        return f"item {wanted[0]}: another batch size counted {again}"
    return None


# ------------------------------------------------------------ csv_aggregate


def table_bytes(seed: int, rows: int, cols: int) -> bytes:
    """``id,c0..`` header + ``rows`` records of ``cols`` integers 0..99999."""
    raw = stream_bytes(seed, "table", 0, rows * cols * 3)
    lines = ["id," + ",".join(f"c{c}" for c in range(cols)) + "\n"]
    at = 0
    for r in range(rows):
        values = []
        for _ in range(cols):
            values.append(str(int.from_bytes(raw[at : at + 3], "little") % 100_000))
            at += 3
        lines.append(f"{r}," + ",".join(values) + "\n")
    return "".join(lines).encode("ascii")


AGGREGATE_HEADER: Final = "id,sum,min,max,digest\n"


def aggregate_line(record: str, rounds: int) -> str:
    fields = record.split(",")
    values = [int(v) for v in fields[1:]]
    digest = record.encode("ascii")
    for _ in range(rounds):
        digest = hashlib.sha256(digest).digest()
    return (
        f"{fields[0]},{sum(values)},{min(values)},{max(values)},{digest.hex()[:16]}\n"
    )


def _agg_params(params: Mapping[str, Any]) -> tuple[int, int, int]:
    return (
        _int(params, "rows", 1, 100_000),
        _int(params, "cols", 1, 64),
        _int(params, "rounds", 1, 20_000),
    )


def _records(items: bytes) -> list[str]:
    lines = items.decode("ascii").splitlines()
    if not lines or not lines[0].startswith("id,"):
        raise KernelParamsError("the items file does not start with the table header")
    return [line for line in lines[1:] if line]


def _agg_run(params: Mapping[str, Any], seed: int, items: bytes) -> dict[str, bytes]:
    _rows, _cols, rounds = _agg_params(params)
    body = "".join(aggregate_line(r, rounds) for r in _records(items))
    return {"aggregates.csv": (AGGREGATE_HEADER + body).encode("ascii")}


def _agg_check(
    params: Mapping[str, Any], seed: int, items: bytes, out: Mapping[str, bytes]
) -> str | None:
    _rows, cols, rounds = _agg_params(params)
    records = _records(items)
    lines = out["aggregates.csv"].decode("ascii").splitlines()
    if lines[0] + "\n" != AGGREGATE_HEADER or len(lines) - 1 != len(records):
        return f"{len(lines) - 1} aggregate rows for {len(records)} records"
    ids = [int(r.split(",", 1)[0]) for r in records]
    if ids != list(range(ids[0], ids[0] + len(ids))):
        return "the chunk's record ids are not consecutive"
    first = records[0].split(",")
    if len(first) != cols + 1:
        return f"record {first[0]} has {len(first) - 1} values, expected {cols}"
    values = [int(v) for v in first[1:]]
    digest = records[0].encode("ascii")
    for _ in range(rounds):
        digest = hashlib.new("sha256", digest).digest()
    again = f"{first[0]},{sum(values)},{min(values)},{max(values)},{digest.hex()[:16]}"
    if lines[1] != again:
        return f"record {first[0]}: the second computation disagrees"
    return None


def _image_params_check(params: Mapping[str, Any]) -> None:
    _image_params(params)


def _hash_params_check(params: Mapping[str, Any]) -> None:
    _hash_params(params)


def _mc_params_check(params: Mapping[str, Any]) -> None:
    _mc_params(params)


def _agg_params_check(params: Mapping[str, Any]) -> None:
    _agg_params(params)


SPLIT_KERNELS: Final[dict[str, SplitKernel]] = {
    "split.image_classify": SplitKernel(
        _image_run, _image_check, _image_params_check, "image"
    ),
    "split.hash_files": SplitKernel(_hash_run, _hash_check, _hash_params_check, "file"),
    "split.montecarlo_range": SplitKernel(
        _mc_run, _mc_check, _mc_params_check, "point set"
    ),
    "split.csv_aggregate": SplitKernel(_agg_run, _agg_check, _agg_params_check, "row"),
}


def run_items(
    family: str, params: Mapping[str, Any], seed: int, items: bytes
) -> tuple[dict[str, bytes], str | None, int]:
    """One chunk in-process: (output files, check problem or None, compute ns)
    - the code :func:`main` runs, for the library and tests."""
    kernel = SPLIT_KERNELS.get(family)
    if kernel is None:
        raise KernelParamsError(f"unknown split family {family!r}")
    if isinstance(seed, bool) or not isinstance(seed, int) or not 0 <= seed < 2**32:
        raise KernelParamsError(f"seed: must be an integer 0..{2**32 - 1}")
    if not isinstance(params, Mapping):
        raise KernelParamsError("params: expected an object")
    kernel.check_params(params)
    started = time.perf_counter_ns()
    files = kernel.run(params, seed, items)
    compute_ns = time.perf_counter_ns() - started
    return files, kernel.check(params, seed, items, files), compute_ns


def _write(out: Path, files: Mapping[str, bytes]) -> None:
    out.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        (out / name).write_bytes(data)


def main(argv: Sequence[str] | None = None) -> int:
    """``run_chunk.py {items_file} {chunk_index} {out}`` (module docstring)."""
    args = list(sys.argv[1:] if argv is None else argv)
    if len(args) != 3:
        print("usage: run_chunk.py ITEMS_FILE CHUNK_INDEX OUT", file=sys.stderr)  # noqa: T201
        return EXIT_BAD_PARAMS
    items_file, chunk, out = args
    try:
        request = json.loads(Path(PARAMS_FILE).read_text(encoding="utf-8"))
        family, params, seed = request["family"], request["params"], request["seed"]
        items = Path(items_file).read_bytes()
        files, problem, compute_ns = run_items(family, params, seed, items)
    except (KernelParamsError, KeyError, TypeError, ValueError, OSError) as exc:
        print(f"benchmark chunk {chunk}: bad request: {exc}", file=sys.stderr)  # noqa: T201
        return EXIT_BAD_PARAMS
    _write(Path(out), files)
    print(  # noqa: T201
        f"benchmark chunk {chunk}: {family} {canonical_json(params)} "
        f"compute_ms={compute_ns / 1e6:.3f} check={'failed' if problem else 'ok'}",
        flush=True,
    )
    if problem is not None:
        print(f"benchmark chunk {chunk}: self-check failed: {problem}", file=sys.stderr)  # noqa: T201
        return EXIT_CHECK_FAILED
    return 0
