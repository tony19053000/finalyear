"""Job-side kernels of the Mode 3 benchmark families (V0.10 G8, D272).

Copied into every split family's job folder as ``bench_kernels/split.py``
(with ``_support``); the job's entrypoint ``run_chunk.py`` calls :func:`main`
**once per chunk** with the D260 placeholders::

    python run_chunk.py {items_file} {chunk_index} {out}

It reads ``workload_params.json`` (family, params, seed) from the working
directory, runs the family over the chunk's items, writes the chunk's output
files into ``{out}`` and **checks its own chunk** (an independent second
computation of some items, plus the family's invariants). A failed check
exits :data:`EXIT_CHECK_FAILED` (4) - the chunk fails (``user_error``), is
retried on another node, and twice failed fails the job: never a wrong
output labelled done (checklist 32).

**Output is chunking-independent.** Every family writes one line / element
per item, in item order; the combine joins the parts in chunk order
(``concat`` / ``merge-csv`` / ``merge-json``) - so the combined output of a
split run and of a one-chunk ("don't split") run are byte-identical
(criterion 1, D269). Every computation is exact or IEEE-deterministic
(integer arithmetic for the CNN, hashes, one numpy PCG64 stream per item), so
it is the same on every laptop.

The data a job reads is part of its project tree (``data/``), generated by
the library from the seed with :func:`stream_bytes` (SHAKE-256: stable across
machines and Python versions, D222); nothing is downloaded.

Families (``meshforge.bench.workloads.split`` holds their parameter models):

* ``split.image_classify`` - ``glob data/img/*.ppm``; a small CNN in **integer**
  arithmetic (fixed weights built in code) labels each image -> ``predictions.csv``
  (``concat``). Check: the first and last image again through a direct
  (loop) convolution instead of the im2col matrix product.
* ``split.hash_files`` - ``glob data/files/*.bin``; ``rounds`` chained SHA-256
  passes + zlib level 6 per file -> ``hashes.csv`` (``concat``). Check: zlib
  round trip and the hash again in 64 KiB pieces.
* ``split.montecarlo_range`` - ``range 0..items``; ``samples`` points per item
  from its own PCG64 stream -> ``results.json`` (``merge-json``). Check: every
  item within 7 standard deviations of pi/4, the first item again with another
  batch size.
* ``split.csv_aggregate`` - ``lines data/table.csv`` (header); per row its sum,
  min, max and a ``rounds``-deep SHA-256 chain -> ``aggregates.csv``
  (``merge-csv``). Check: one output row per record, ids consecutive, the
  first row again.
"""

