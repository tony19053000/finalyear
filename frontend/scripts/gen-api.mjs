// Typed API client source (V0.8 G2, D171).
//
//   node scripts/gen-api.mjs           # openapi.json -> src/api/schema.d.ts
//   node scripts/gen-api.mjs --check   # exit 1 if schema.d.ts is stale
//   node scripts/gen-api.mjs --console [--check]
//       # V0.17 G3: console-openapi.json -> src/agentConsole/schema.d.ts
//
// frontend/openapi.json is exported by `scripts/export_openapi.py` (no server)
// and committed; `npm run gen:api` runs both steps. The output's first line
// records the SHA-256 of the openapi.json it came from, so the Python drift
// test (tests/unit/test_v08_g2_openapi_drift.py) can prove schema.d.ts was
// regenerated from the committed spec without needing Node.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const consoleTarget = process.argv.includes("--console");
const specName = consoleTarget ? "console-openapi.json" : "openapi.json";
const outRel = consoleTarget ? "src/agentConsole/schema.d.ts" : "src/api/schema.d.ts";
const specPath = fileURLToPath(new URL(`../${specName}`, import.meta.url));
const outPath = fileURLToPath(new URL(`../${outRel}`, import.meta.url));

const HEADER_PREFIX = `// ${specName} sha256: `;

const specText = readFileSync(specPath, "utf8");
const digest = createHash("sha256").update(specText, "utf8").digest("hex");
const ast = await openapiTS(JSON.parse(specText), {
  // Sorted members: a backend change shows up as a small, stable diff.
  alphabetize: true,
  exportType: false,
});
const body = astToString(ast);
const text =
  `${HEADER_PREFIX}${digest}\n` +
  `// GENERATED by frontend/scripts/gen-api.mjs from frontend/${specName} - do not edit.\n` +
  `// Regenerate: cd frontend && npm run ${consoleTarget ? "gen:console-api" : "gen:api"}\n\n` +
  body;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    // missing = stale
  }
  if (current !== text) {
    console.error(`gen-api: ${outRel} is out of date - run \`npm run ${consoleTarget ? "gen:console-api" : "gen:api"}\``);
    process.exit(1);
  }
  console.log(`gen-api: ${outRel} is up to date`);
} else {
  writeFileSync(outPath, text, "utf8");
  console.log(`gen-api: wrote ${outRel} (${specName} sha256 ${digest.slice(0, 12)})`);
}
