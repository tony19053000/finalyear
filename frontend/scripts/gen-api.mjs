// Typed API client source (V0.8 G2, D171).
//
//   node scripts/gen-api.mjs           # openapi.json -> src/api/schema.d.ts
//   node scripts/gen-api.mjs --check   # exit 1 if schema.d.ts is stale
//
// frontend/openapi.json is exported by `scripts/export_openapi.py` (no server)
// and committed; `npm run gen:api` runs both steps. The output's first line
// records the SHA-256 of the openapi.json it came from, so the Python drift
// test (tests/unit/test_v08_g2_openapi_drift.py) can prove schema.d.ts was
// regenerated from the committed spec without needing Node.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const specPath = fileURLToPath(new URL("../openapi.json", import.meta.url));
const outPath = fileURLToPath(new URL("../src/api/schema.d.ts", import.meta.url));

const HEADER_PREFIX = "// openapi.json sha256: ";

const specText = readFileSync(specPath, "utf8");
const digest = createHash("sha256").update(specText, "utf8").digest("hex");
const ast = await openapiTS(JSON.parse(specText), {
  // Sorted members: a backend change shows up as a small, stable diff.
  alphabetize: true,
  exportType: false,
});
const body = astToString(ast);
const text =
  `${HEADER_PREFIX}${digest}\n` +
  "// GENERATED by frontend/scripts/gen-api.mjs from frontend/openapi.json - do not edit.\n" +
  "// Regenerate: cd frontend && npm run gen:api\n\n" +
  body;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    // missing = stale
  }
  if (current !== text) {
    console.error("gen-api: src/api/schema.d.ts is out of date - run `npm run gen:api`");
    process.exit(1);
  }
  console.log("gen-api: src/api/schema.d.ts is up to date");
} else {
  writeFileSync(outPath, text, "utf8");
  console.log(`gen-api: wrote src/api/schema.d.ts (openapi.json sha256 ${digest.slice(0, 12)})`);
}
