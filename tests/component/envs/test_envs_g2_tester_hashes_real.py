"""V0.5 G2 tester round 3: a pip-compile --generate-hashes style file through real
uv (offline wheelhouse). Right hashes build; wrong hashes fail typed and cache
nothing; hashes on dependency lines are enforced."""

from __future__ import annotations

import base64
import hashlib
import subprocess
import zipfile
from pathlib import Path

import pytest

pytest.importorskip("uv", reason="needs the agent extra (the uv wheel)")

from mf_envs_support import offline_builder

from meshforge.agent.envs import EnvError

pytestmark = [pytest.mark.timeout(180)]


def _wheel(folder: Path, name: str, version: str, requires: str = "") -> str:
    folder.mkdir(parents=True, exist_ok=True)
    dist = f"{name}-{version}.dist-info"
    meta = f"Metadata-Version: 2.1\nName: {name}\nVersion: {version}\n"
    if requires:
        meta += f"Requires-Dist: {requires}\n"
    files = {
        f"{name}/__init__.py": f'VERSION = "{version}"\n'.encode(),
        f"{dist}/METADATA": meta.encode(),
        f"{dist}/WHEEL": (
            b"Wheel-Version: 1.0\nGenerator: t\nRoot-Is-Purelib: true\n"
            b"Tag: py3-none-any\n"
        ),
    }
    rec = []
    for n, d in files.items():
        h = base64.urlsafe_b64encode(hashlib.sha256(d).digest()).rstrip(b"=").decode()
        rec.append(f"{n},sha256={h},{len(d)}")
    rec.append(f"{dist}/RECORD,,")
    files[f"{dist}/RECORD"] = ("\n".join(rec) + "\n").encode()
    path = folder / f"{name}-{version}-py3-none-any.whl"
    with zipfile.ZipFile(path, "w") as zf:
        for n, d in files.items():
            zf.writestr(n, d)
    return hashlib.sha256(path.read_bytes()).hexdigest()


@pytest.fixture
def world(tmp_path: Path) -> tuple[Path, dict[str, str]]:
    wheels = tmp_path / "wheels"
    hashes = {
        "app": _wheel(wheels, "mfapp", "1.0", "mfdep==2.0"),
        "dep": _wheel(wheels, "mfdep", "2.0"),
    }
    return wheels, hashes


def _file(
    h: dict[str, str], *, app: str | None = None, dep: str | None = None
) -> bytes:
    app = app or h["app"]
    dep = dep or h["dep"]
    return (
        "# autogenerated by pip-compile --generate-hashes\n"
        "mfapp==1.0 \\\n"
        f"    --hash=sha256:{'0' * 64} \\\n"  # an extra, non-matching hash is fine
        f"    --hash=sha256:{app}\n"
        "    # via -r requirements.in\n"
        "mfdep==2.0 \\\n"
        f"    --hash=sha256:{dep}\n"
        "    # via mfapp\n"
    ).encode()


def _import(python: str | Path, env: dict[str, str] | None = None) -> str:
    out = subprocess.run(
        [
            str(python),
            "-I",
            "-c",
            "import mfapp, mfdep; print(mfapp.VERSION, mfdep.VERSION)",
        ],
        capture_output=True,
        text=True,
        timeout=60,
        env=env,
    )
    return out.stdout.strip()


def _names(root: Path, kind: str) -> list[str]:
    folder = root / kind
    return sorted(p.name for p in folder.iterdir()) if folder.exists() else []


@pytest.mark.asyncio
async def test_hashed_file_builds_a_venv_and_then_hits(
    tmp_path: Path, world: tuple[Path, dict[str, str]]
) -> None:
    wheels, h = world
    b = offline_builder(tmp_path / "envs", wheels)
    built = await b.ensure_venv(python=None, requirements=_file(h), deadline=1e18)
    assert built.cache == "built"
    assert _import(built.python) == "1.0 2.0"
    # same file written differently (hash order, CRLF, extra comments) -> same env
    noisy = _file(h).replace(b"\n", b"\r\n") + b"# trailing\n"
    again = await b.ensure_venv(python=None, requirements=noisy, deadline=1e18)
    assert again.cache == "hit" and again.env_hash == built.env_hash


@pytest.mark.asyncio
@pytest.mark.parametrize("which", ["app", "dep"])
@pytest.mark.parametrize("kind", ["venv", "subprocess"])
async def test_a_wrong_hash_fails_typed_and_caches_nothing(
    tmp_path: Path, world: tuple[Path, dict[str, str]], which: str, kind: str
) -> None:
    wheels, h = world
    b = offline_builder(tmp_path / "envs", wheels)
    bad = _file(h, **{which: "f" * 64})
    # the 'app' file also lists the zero hash, so make the app line wrong entirely
    bad = bad.replace(f"    --hash=sha256:{'0' * 64} \\\n".encode(), b"")
    build = (
        b.ensure_venv(python=None, requirements=bad, deadline=1e18)
        if kind == "venv"
        else b.ensure_target(requirements=bad, deadline=1e18)
    )
    with pytest.raises(EnvError) as info:
        await build
    assert info.value.reason == "setup_failed"
    assert _names(tmp_path / "envs", kind) == []  # no env, no .building left
    # and the corrected file then builds fine (nothing poisoned)
    ok = _file(h)
    if kind == "venv":
        assert (
            await b.ensure_venv(python=None, requirements=ok, deadline=1e18)
        ).cache == "built"
    else:
        assert (await b.ensure_target(requirements=ok, deadline=1e18)).cache == "built"


@pytest.mark.asyncio
async def test_a_tampered_wheel_in_the_wheelhouse_is_not_installed(
    tmp_path: Path, world: tuple[Path, dict[str, str]]
) -> None:
    wheels, h = world
    req = _file(h)
    _wheel(wheels, "mfdep", "2.0", "")  # rewrite: same bytes? change content below
    with zipfile.ZipFile(wheels / "mfdep-2.0-py3-none-any.whl", "a") as zf:
        zf.writestr("mfdep/evil.py", "x = 1\n")
    b = offline_builder(tmp_path / "envs", wheels)
    with pytest.raises(EnvError):
        await b.ensure_venv(python=None, requirements=req, deadline=1e18)
    assert _names(tmp_path / "envs", "venv") == []
