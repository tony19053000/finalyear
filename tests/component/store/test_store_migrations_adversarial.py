# Contains @ : / % # - the characters most likely to break naive URL handling.
SPECIAL_PASSWORD = "p@ss:/word%#!"


def _run_as_superuser(settings: DatabaseSettings, *statements: str) -> None:
    import asyncio

    async def go() -> None:
        engine = create_engine(settings)
        try:
            async with engine.begin() as conn:
                for statement in statements:
                    await conn.execute(text(statement))
        finally:
            await engine.dispose()

    asyncio.run(go())


_SQL_IDENT = re.compile(r"^[a-z0-9_]+$")


def _checked_ident(name: str) -> str:
    """Refuse any role/db name that is not plain ``[a-z0-9_]+`` before it is
    interpolated into SQL (identifiers cannot be bound as query parameters)."""
    assert _SQL_IDENT.fullmatch(name), f"unsafe SQL identifier {name!r}"
    return name


@pytest.fixture
def special_char_pg_settings(
    pg_settings: DatabaseSettings,
) -> Iterator[DatabaseSettings]:
    """A login role with a URL-hostile password that owns this test's fresh database.

    The shared session container's superuser is left untouched (other tests use
    it); the role is unique per test and removed again afterwards.
    """
    role = _checked_ident(f"mf_special_{new_job_id().lower()[-12:]}")
    _checked_ident(pg_settings.name)
    # Not an f-string injection concern: fixed, test-controlled names and password.
    # The try starts before CREATE ROLE so a failure in ALTER DATABASE (or anywhere
    # after the role exists) still removes the role; roles are cluster-wide and
    # would otherwise leak into the shared session container.
    try:
        _run_as_superuser(
            pg_settings,
            f"CREATE ROLE \"{role}\" LOGIN PASSWORD '{SPECIAL_PASSWORD}'",
            f'ALTER DATABASE "{pg_settings.name}" OWNER TO "{role}"',
        )
        yield pg_settings.model_copy(
            update={"user": role, "password": SecretStr(SPECIAL_PASSWORD)}
        )
    finally:
        _drop_role_if_exists(pg_settings, role)


def _drop_role_if_exists(settings: DatabaseSettings, role: str) -> None:
    """Idempotent role cleanup: safe whether or not CREATE ROLE ever succeeded."""
    _checked_ident(role)
    _checked_ident(settings.user)
    _run_as_superuser(
        settings,
        # Role/user names are generated by this test file, never external input.
        f"""
        DO $$
        BEGIN
            IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{role}') THEN
                EXECUTE 'REASSIGN OWNED BY "{role}" TO "{settings.user}"';
                EXECUTE 'DROP OWNED BY "{role}"';
            END IF;
        END
        $$
        """,  # noqa: S608
        f'DROP ROLE IF EXISTS "{role}"',
    )


def test_special_char_password_round_trips_through_real_postgres(
    special_char_pg_settings: DatabaseSettings,
) -> None:
    """Passwords with @ : / % # must work end-to-end, not just in URL-building unit tests."""
    cfg = alembic_config(special_char_pg_settings)
    command.upgrade(cfg, "head")
    try:
        command.check(cfg)
    finally:
        command.downgrade(cfg, "base")

    # Field-based settings AND an equivalent full URL must both authenticate.
    url_settings = DatabaseSettings(url=special_char_pg_settings.url_secret())
    cfg2 = alembic_config(url_settings)
    command.upgrade(cfg2, "head")
    command.downgrade(cfg2, "base")


def test_url_query_parameters_are_preserved_and_asyncpg_compatible_ssl_works(
    special_char_pg_settings: DatabaseSettings,
) -> None:
    """A ``?ssl=disable`` query param (asyncpg's own, not psycopg's ``sslmode``) must
    not be dropped by URL normalisation and must still let a real connection through."""
    base_url = special_char_pg_settings.url_secret().get_secret_value()
    settings = DatabaseSettings(url=SecretStr(f"{base_url}?ssl=disable"))
    assert settings.url_secret().get_secret_value().endswith("?ssl=disable")

    cfg = alembic_config(settings)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")


def test_psycopg_style_sslmode_query_param_fails_with_typed_error_not_a_crash(
    special_char_pg_settings: DatabaseSettings,
) -> None:
    """``sslmode`` is a psycopg convention; asyncpg's ``connect()`` rejects it. This
    must surface as our typed, password-masked ``DatabaseUnavailableError`` -
    never an unhandled traceback leaking the password, and never a hang."""
    base_url = special_char_pg_settings.url_secret().get_secret_value()
    settings = DatabaseSettings(url=SecretStr(f"{base_url}?sslmode=disable"))

    async def go() -> None:
        engine = create_engine(settings)
        try:
            await check_connection(engine, settings)
        finally:
            await engine.dispose()

    import asyncio

    start = time.monotonic()
    with pytest.raises(DatabaseUnavailableError) as info:
        asyncio.run(go())
    elapsed = time.monotonic() - start
    assert elapsed < 5, f"unsupported query param should fail fast, took {elapsed}s"
    assert SPECIAL_PASSWORD not in f"{info.value} {info.value.to_dict()}"


def test_offline_sql_generation_needs_no_database_at_all() -> None:
    """``alembic upgrade head --sql`` must work with zero network access."""
    unreachable = DatabaseSettings(host="203.0.113.1", port=1, connect_timeout_s=1)
    cfg = alembic_config(unreachable)

    import io
    from contextlib import redirect_stdout

    buf = io.StringIO()
    with redirect_stdout(buf):
        command.upgrade(cfg, "head", sql=True)
    output = buf.getvalue()
    assert "CREATE TABLE alembic_version" in output
    assert "INSERT INTO alembic_version" in output
    assert "0001" in output


def test_unreachable_database_fails_within_configured_timeout_no_hang() -> None:
    """A DB that never answers (blackholed port) must fail close to
    ``connect_timeout_s``, not hang indefinitely and not take much longer."""
    settings = DatabaseSettings(
        host="203.0.113.1",  # TEST-NET-3 (RFC 5737): reserved, guaranteed unroutable
        port=5432,
        connect_timeout_s=2,
    )

    async def go() -> None:
        engine = create_engine(settings)
        try:
            await check_connection(engine, settings)
        finally:
            await engine.dispose()

    import asyncio

    start = time.monotonic()
    with pytest.raises(DatabaseUnavailableError):
        asyncio.run(go())
    elapsed = time.monotonic() - start
    assert elapsed < 10, f"connect_timeout_s=2 should bound the wait, took {elapsed}s"


async def _table_names(engine: AsyncEngine) -> set[str]:
    from sqlalchemy import inspect

    async with engine.connect() as conn:
        return await conn.run_sync(
            lambda c: set(inspect(c).get_table_names(schema="public"))
        )


def test_downgrade_base_is_idempotent_when_already_at_base(
    special_char_pg_settings: DatabaseSettings,
) -> None:
    """Calling ``downgrade base`` twice in a row (e.g. a retried lab script) must
    not error even though there is nothing left to downgrade."""
    cfg = alembic_config(special_char_pg_settings)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")
    command.downgrade(cfg, "base")  # no-op, must not raise

    async def go() -> set[str]:
        engine = create_engine(special_char_pg_settings)
        try:
            return await _table_names(engine)
        finally:
            await engine.dispose()

    import asyncio

    tables = asyncio.run(go())
    assert tables <= {"alembic_version"}


def test_check_connection_select1_against_real_postgres(
    special_char_pg_settings: DatabaseSettings,
) -> None:
    """Sanity: the ``SELECT 1`` health check itself succeeds against a real,
    reachable database (paired with the unreachable-DB test above)."""

    async def go() -> None:
        engine = create_engine(special_char_pg_settings)
        try:
            await check_connection(engine, special_char_pg_settings)
            async with engine.connect() as conn:
                assert (await conn.execute(text("SELECT 1"))).scalar_one() == 1
        finally:
            await engine.dispose()

    import asyncio

    asyncio.run(go())
