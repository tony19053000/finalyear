class _TBase(DeclarativeBase):
    """Separate metadata (same convention) so test tables never leak into Base."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map = Base.type_annotation_map


class _Thing(TimestampMixin, _TBase):
    __tablename__ = "mf_test_thing"
    id: Mapped[str] = id_column(primary_key=True)
    label: Mapped[str] = mapped_column(String(20))


def _run[T](coro: Coroutine[Any, Any, T]) -> T:
    return asyncio.run(coro)


async def _snapshot(settings: DatabaseSettings) -> tuple[set[str], list[str]]:
    engine: AsyncEngine = create_engine(settings)
    try:
        async with engine.connect() as conn:
            tables = await conn.run_sync(
                lambda c: set(inspect(c).get_table_names(schema="public"))
            )
            versions: list[str] = []
            if "alembic_version" in tables:
                rows = await conn.execute(
                    text("SELECT version_num FROM alembic_version")
                )
                versions = [r[0] for r in rows]
        return tables, versions
    finally:
        await engine.dispose()


HEAD = "0020"  # bump with every new migration; the chain must stay linear


def test_single_linear_head() -> None:
    script = ScriptDirectory.from_config(alembic_config())
    assert script.get_heads() == [HEAD]
    chain = [r.revision for r in script.walk_revisions()]
    assert chain == [
        "0020",
        "0019",
        "0018",
        "0017",
        "0016",
        "0015",
        "0014",
        "0013",
        "0012",
        "0011",
        "0010",
        "0009",
        "0008",
        "0007",
        "0006",
        "0005",
        "0004",
        "0003",
        "0002",
        "0001",
    ]  # head first, base last
    base = script.get_revision("0001")
    assert base is not None
    assert base.down_revision is None
    head = script.get_revision(HEAD)
    assert head is not None
    assert head.down_revision == "0019"


def test_upgrade_check_downgrade_on_clean_database(
    pg_settings: DatabaseSettings,
) -> None:
    cfg = alembic_config(pg_settings)

    tables, _ = _run(_snapshot(pg_settings))
    assert tables == set(), f"database not clean: {tables}"

    command.upgrade(cfg, "head")
    tables, versions = _run(_snapshot(pg_settings))
    assert "alembic_version" in tables
    assert versions == [HEAD]
    assert {"node", "node_session"} <= tables

    command.check(cfg)  # raises AutogenerateDiffsDetected if models != migrations

    command.upgrade(cfg, "head")  # idempotent
    assert _run(_snapshot(pg_settings))[1] == [HEAD]

    command.downgrade(cfg, "base")
    tables, versions = _run(_snapshot(pg_settings))
    assert tables <= {"alembic_version"}
    assert versions == []

    command.upgrade(cfg, "head")  # re-upgrade after full downgrade works
    assert _run(_snapshot(pg_settings))[1] == [HEAD]
    command.downgrade(cfg, "base")


def test_sessions_run_in_utc_and_timestamptz_roundtrips(
    pg_settings: DatabaseSettings,
) -> None:
    """The engine's connect args (timezone=UTC) give aware UTC datetimes back."""

    async def go() -> None:
        engine = create_engine(pg_settings)
        try:
            async with engine.connect() as conn:
                tz = (await conn.execute(text("SHOW timezone"))).scalar_one()
                app = (await conn.execute(text("SHOW application_name"))).scalar_one()
                now = (await conn.execute(text("SELECT now()").columns())).scalar_one()
            assert tz == "UTC"
            assert app == "meshforge-controller"
            assert now.utcoffset() is not None
            assert now.utcoffset().total_seconds() == 0
        finally:
            await engine.dispose()

    _run(go())


def test_timestamp_mixin_against_real_postgres(pg_settings: DatabaseSettings) -> None:
    """created_at/updated_at are set by the DB; updated_at moves on UPDATE."""
    TBase, Thing = _TBase, _Thing

    async def go() -> None:
        engine = create_engine(pg_settings)
        try:
            async with engine.begin() as conn:
                await conn.run_sync(TBase.metadata.create_all)
            factory = create_session_factory(engine)
            thing_id = new_job_id()
            async with factory() as session, session.begin():
                session.add(Thing(id=thing_id, label="a"))
            async with factory() as session:
                row = (await session.execute(select(Thing))).scalar_one()
                created, updated = row.created_at, row.updated_at
                offset = created.utcoffset()
                assert offset is not None
                assert offset.total_seconds() == 0
            async with factory() as session, session.begin():
                await session.execute(
                    update(Thing).where(Thing.id == thing_id).values(label="b")
                )
            async with factory() as session:
                row = (await session.execute(select(Thing))).scalar_one()
                assert row.created_at == created
                assert row.updated_at > updated
            async with engine.connect() as conn:
                cols = await conn.run_sync(
                    lambda c: {
                        col["name"]: col
                        for col in inspect(c).get_columns("mf_test_thing")
                    }
                )
                assert isinstance(cols["created_at"]["type"], DateTime)
                assert cols["created_at"]["type"].timezone is True
                pk = await conn.run_sync(
                    lambda c: inspect(c).get_pk_constraint("mf_test_thing")
                )
                assert pk["name"] == "pk_mf_test_thing"
            async with engine.begin() as conn:
                await conn.run_sync(TBase.metadata.drop_all)
        finally:
            await engine.dispose()

    _run(go())


def test_unreachable_database_raises_typed_error() -> None:
    settings = DatabaseSettings(
        host="127.0.0.1", port=1, password=SecretStr("nope-secret"), connect_timeout_s=2
    )

    async def go() -> None:
        engine = create_engine(settings)
        try:
            await check_connection(engine, settings)
        finally:
            await engine.dispose()

    with pytest.raises(DatabaseUnavailableError) as info:
        _run(go())
    assert "nope-secret" not in f"{info.value} {info.value.to_dict()}"
    assert info.value.retryable


def test_alembic_cli_uses_settings_env(
    pg_settings: DatabaseSettings, tmp_path: Path
) -> None:
    """The developer path: `alembic upgrade head` / `downgrade base` from the repo root
    with the URL only in MESHFORGE_DATABASE__URL (never in alembic.ini)."""
    import os

    env = {k: v for k, v in os.environ.items() if not k.startswith("MESHFORGE_")}
    env["MESHFORGE_DATABASE__URL"] = pg_settings.url_secret().get_secret_value()
    env["XDG_CONFIG_HOME"] = str(tmp_path)  # no user config.toml can interfere
    alembic = [sys.executable, "-m", "alembic"]
    for args in (["upgrade", "head"], ["current"], ["downgrade", "base"]):
        result = subprocess.run(
            [*alembic, *args],
            cwd=REPO_ROOT,
            env=env,
            capture_output=True,
            text=True,
            timeout=120,
            check=False,
        )
        assert result.returncode == 0, f"alembic {args}: {result.stderr}"
        assert "mf-test-pw" not in result.stdout + result.stderr
    assert _run(_snapshot(pg_settings))[1] == []
