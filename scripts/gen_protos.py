#!/usr/bin/env python3
"""Generate or check MeshForge protobuf/gRPC Python code (roadmap task 0.1.5).

Source of truth: ``proto/meshforge/v1/*.proto`` (proto package ``meshforge.v1``).
Output (committed): ``src/meshforge/common/proto/meshforge/v1/`` ->
``meshforge.common.proto.meshforge.v1.{agent,common,gpu}_pb2[_grpc]`` with
``.pyi`` stubs from mypy-protobuf.

Usage (from anywhere; uses the current interpreter, no shell)::

    uv run python scripts/gen_protos.py           # regenerate in place
    uv run python scripts/gen_protos.py --check   # exit 1 if committed code drifted

How imports are made to resolve
-------------------------------
protoc derives Python import statements from the *proto file path*: a file that
imports ``meshforge/v1/common.proto`` gets ``from meshforge.v1 import common_pb2``.
That module does not exist in our package layout. Instead of baking the Python
layout into the .proto import paths (which would leak into every other language
and into the descriptor names), protoc runs with ``-I proto`` so descriptor
names stay canonical (``meshforge/v1/agent.proto``), and this script rewrites
exactly the ``from meshforge.v1 import`` lines to
``from meshforge.common.proto.meshforge.v1 import``. The rewrite is strict: any
other form of import of a generated module makes generation fail, so an
unexpected protoc output change cannot silently produce broken imports.

Determinism
-----------
Protos are passed to protoc in sorted order with relative, ``/``-separated
paths; sources are staged with LF line endings (so a CRLF Windows checkout
generates identical code) and output is normalised to LF; no timestamps or
absolute paths are written.
Tool versions are pinned by ``uv.lock``. ``--check`` compares byte-for-byte.

Version compatibility
---------------------
Generated ``_pb2.py`` files call ``ValidateProtobufRuntimeVersion`` and
``_pb2_grpc.py`` files require ``grpcio>=GRPC_GENERATED_VERSION`` at import
time. This script fails (exit 2) if the gencode version is newer than the
installed runtime *or* newer than the minimum allowed by ``pyproject.toml``
(otherwise a valid install could fail to import the generated code).

Exit codes: 0 ok / up to date, 1 drift found by ``--check``, 2 error.
"""

from __future__ import annotations

import argparse
import difflib
import importlib.metadata
import importlib.resources
import os
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

EXIT_OK = 0
EXIT_DRIFT = 1
EXIT_ERROR = 2

PROTO_DIR = Path("proto")
OUT_DIR = Path("src") / "meshforge" / "common" / "proto"
# Python package that OUT_DIR corresponds to.
OUT_PACKAGE = "meshforge.common.proto"
# Top-level proto path component; all protos must live under proto/<this>/.
PROTO_ROOT_NAME = "meshforge"

HEADER = (
    "# Code generated by scripts/gen_protos.py from proto/. DO NOT EDIT.\n"
    "# Regenerate: uv run python scripts/gen_protos.py\n"
    "# ruff: noqa\n"
    "# fmt: off\n"
    "# mypy: ignore-errors\n"
)
INIT_CONTENT = (
    "# Code generated by scripts/gen_protos.py. DO NOT EDIT.\n"
    '"""Generated protobuf/gRPC code. Sources: proto/ in the repository root."""\n'
)

# Matches imports of generated MeshForge modules as protoc/mypy-protobuf emit
# them: "from meshforge.v1 import agent_pb2 as ...".
_GEN_FROM_IMPORT = re.compile(
    rf"^(?P<indent>[ \t]*)from (?P<mod>{PROTO_ROOT_NAME}(?:\.\w+)*) import ",
    re.MULTILINE,
)
# Any other way of importing a generated module (must not appear after rewrite).
_STRAY_IMPORT = re.compile(
    rf"^[ \t]*(?:import {PROTO_ROOT_NAME}\b|from {PROTO_ROOT_NAME}\b(?!\.common\.proto\b))",
    re.MULTILINE,
)
# `import "meshforge/...";` (optionally public/weak) in a .proto source.
_PROTO_MESHFORGE_IMPORT = re.compile(
    rf'^\s*import\s+(?:public\s+|weak\s+)?"{PROTO_ROOT_NAME}/[^"]+"\s*;',
    re.MULTILINE,
)
_PB_GENCODE_VERSION = re.compile(
    r"ValidateProtobufRuntimeVersion\(\s*_runtime_version\.Domain\.PUBLIC,"
    r"\s*(\d+),\s*(\d+),\s*(\d+),"
)
_GRPC_GENCODE_VERSION = re.compile(r"^GRPC_GENERATED_VERSION = '([^']+)'", re.MULTILINE)


class GenError(Exception):
    """Generation cannot proceed (tooling missing, protoc failed, incompatibility)."""


# ---------------------------------------------------------------------------
# Versions
# ---------------------------------------------------------------------------


def parse_version(text: str) -> tuple[int, int, int]:
    """Leading ``X[.Y[.Z]]`` of a version string, padded to three parts."""
    match = re.match(r"(\d+)(?:\.(\d+))?(?:\.(\d+))?", text.strip())
    if match is None:
        raise GenError(f"cannot parse version {text!r}")
    major, minor, patch = (int(part) if part else 0 for part in match.groups())
    return major, minor, patch


def check_version_compat(
    name: str,
    gencode: tuple[int, int, int],
    runtime: tuple[int, int, int],
    floor: tuple[int, int, int],
) -> None:
    """Raise if code generated at ``gencode`` could fail to import.

    ``runtime`` is the installed version, ``floor`` the minimum permitted by
    ``pyproject.toml``. Generated code requires runtime >= gencode.
    """
    fmt = ".".join
    if gencode > runtime:
        raise GenError(
            f"{name}: generated code targets {fmt(map(str, gencode))} but the installed "
            f"runtime is {fmt(map(str, runtime))}; upgrade {name} or downgrade grpcio-tools"
        )
    if gencode > floor:
        raise GenError(
            f"{name}: generated code targets {fmt(map(str, gencode))} but pyproject.toml "
            f"allows {name}>={fmt(map(str, floor))}; raise the lower bound or downgrade "
            "grpcio-tools"
        )


def _dependency_floor(pyproject: Path, dist: str) -> tuple[int, int, int]:
    data = tomllib.loads(pyproject.read_text(encoding="utf-8"))
    pattern = re.compile(
        rf"^{re.escape(dist)}\s*(?:\[[^\]]*\])?\s*>=\s*([0-9][^,;\s]*)"
    )
    for spec in data.get("project", {}).get("dependencies", []):
        match = pattern.match(spec)
        if match:
            return parse_version(match.group(1))
    raise GenError(
        f"pyproject.toml: no '{dist}>=X' lower bound in [project].dependencies"
    )


def _check_versions(files: dict[str, bytes], pyproject: Path) -> None:
    pb_gencode = grpc_gencode = None
    for rel, data in files.items():
        text = data.decode("utf-8")
        if rel.endswith("_pb2.py") and (m := _PB_GENCODE_VERSION.search(text)):
            found = (int(m.group(1)), int(m.group(2)), int(m.group(3)))
            pb_gencode = max(found, pb_gencode) if pb_gencode else found
        elif rel.endswith("_pb2_grpc.py") and (m := _GRPC_GENCODE_VERSION.search(text)):
            found = parse_version(m.group(1))
            grpc_gencode = max(found, grpc_gencode) if grpc_gencode else found
    if pb_gencode is None or grpc_gencode is None:
        raise GenError("could not find gencode versions in protoc output")
    check_version_compat(
        "protobuf",
        pb_gencode,
        parse_version(importlib.metadata.version("protobuf")),
        _dependency_floor(pyproject, "protobuf"),
    )
    check_version_compat(
        "grpcio",
        grpc_gencode,
        parse_version(importlib.metadata.version("grpcio")),
        _dependency_floor(pyproject, "grpcio"),
    )


# ---------------------------------------------------------------------------
# Generation
# ---------------------------------------------------------------------------


def _find_protos(proto_root: Path) -> list[str]:
    if not proto_root.is_dir():
        raise GenError(f"proto directory not found: {proto_root}")
    protos = sorted(
        p.relative_to(proto_root).as_posix() for p in proto_root.rglob("*.proto")
    )
    if not protos:
        raise GenError(f"no .proto files under {proto_root}")
    stray = [p for p in protos if not p.startswith(f"{PROTO_ROOT_NAME}/")]
    if stray:
        raise GenError(f"protos must live under proto/{PROTO_ROOT_NAME}/: {stray}")
    return protos


def _find_plugin(name: str) -> str:
    exe = name + (".exe" if os.name == "nt" else "")
    candidate = Path(sys.executable).parent / exe
    if candidate.is_file():
        return str(candidate)
    found = shutil.which(name)
    if found:
        return found
    raise GenError(
        f"{name} not found; run `uv sync` (mypy-protobuf is in the dev group)"
    )


def _run_protoc(proto_root: Path, protos: list[str], raw_out: Path) -> None:
    wkt = importlib.resources.files("grpc_tools") / "_proto"
    cmd = [
        sys.executable,
        "-m",
        "grpc_tools.protoc",
        "-I.",
        f"-I{wkt}",
        f"--plugin=protoc-gen-mypy={_find_plugin('protoc-gen-mypy')}",
        f"--plugin=protoc-gen-mypy_grpc={_find_plugin('protoc-gen-mypy_grpc')}",
        f"--python_out={raw_out}",
        f"--grpc_python_out={raw_out}",
        f"--mypy_out={raw_out}",
        f"--mypy_grpc_out={raw_out}",
        *protos,
    ]
    result = subprocess.run(
        cmd,
        cwd=proto_root,
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=False,
    )
    if result.returncode != 0:
        raise GenError(f"protoc failed (exit {result.returncode}):\n{result.stderr}")


def _rewrite_imports(text: str, rel: str) -> tuple[str, int]:
    """Rewrite generated-module imports; return the new text and rewrite count."""

    def repl(match: re.Match[str]) -> str:
        return f"{match['indent']}from {OUT_PACKAGE}.{match['mod']} import "

    text, count = _GEN_FROM_IMPORT.subn(repl, text)
    stray = _STRAY_IMPORT.search(text)
    if stray:
        raise GenError(f"{rel}: unexpected import form {stray.group(0).strip()!r}")
    return text, count


def _protos_importing_meshforge(proto_root: Path, protos: list[str]) -> set[str]:
    """Protos (relative paths) that import at least one other MeshForge proto."""
    return {
        rel
        for rel in protos
        if _PROTO_MESHFORGE_IMPORT.search(
            (proto_root / rel).read_text(encoding="utf-8")
        )
    }


def _postprocess(
    raw_out: Path, needs_rewrite: set[str] | None = None
) -> dict[str, bytes]:
    """Relative POSIX path (under OUT_DIR) -> final file content.

    ``needs_rewrite`` lists protos that import other MeshForge protos; their
    ``_pb2.py`` must contain at least one rewritten import, otherwise protoc's
    import form changed and the regex silently stopped matching.
    """
    expected_rewrites = {
        rel.removesuffix(".proto") + "_pb2.py" for rel in (needs_rewrite or set())
    }
    files: dict[str, bytes] = {}
    for path in sorted(raw_out.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(raw_out).as_posix()
        if path.suffix not in {".py", ".pyi"}:
            raise GenError(f"unexpected protoc output file: {rel}")
        text = path.read_bytes().decode("utf-8").replace("\r\n", "\n")
        text, rewrites = _rewrite_imports(text, rel)
        if rel in expected_rewrites and rewrites == 0:
            raise GenError(
                f"{rel}: its proto imports other {PROTO_ROOT_NAME} protos but no import "
                "was rewritten; protoc's import form changed, update _GEN_FROM_IMPORT"
            )
        expected_rewrites.discard(rel)
        if not text.endswith("\n"):
            text += "\n"
        files[rel] = (HEADER + text).encode("utf-8")
    if expected_rewrites:
        raise GenError(f"protoc produced no output for: {sorted(expected_rewrites)}")
    # Package markers for OUT_DIR and every generated directory.
    dirs = {""}
    for rel in list(files):
        parts = rel.split("/")[:-1]
        dirs.update("/".join(parts[:i]) for i in range(1, len(parts) + 1))
    for d in dirs:
        files[f"{d}/__init__.py" if d else "__init__.py"] = INIT_CONTENT.encode("utf-8")
    return dict(sorted(files.items()))


def _stage_lf_sources(proto_root: Path, protos: list[str], staged: Path) -> None:
    """Copy protos to ``staged`` with CRLF/CR normalised to LF.

    protoc copies comments into the generated ``.pyi`` docstrings; with CRLF
    sources an empty ``//`` line becomes ``"\\r"`` and mypy-protobuf indents it,
    so a Windows ``core.autocrlf`` checkout would produce different output.
    """
    for rel in protos:
        data = (
            (proto_root / rel)
            .read_bytes()
            .replace(b"\r\n", b"\n")
            .replace(b"\r", b"\n")
        )
        target = staged / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)


def generate(repo_root: Path) -> dict[str, bytes]:
    """Run protoc into a temp dir and return the final generated tree in memory."""
    proto_root = repo_root / PROTO_DIR
    protos = _find_protos(proto_root)
    with tempfile.TemporaryDirectory(prefix="meshforge-protos-") as tmp:
        staged = Path(tmp) / "src"
        raw_out = Path(tmp) / "out"
        raw_out.mkdir()
        _stage_lf_sources(proto_root, protos, staged)
        _run_protoc(staged, protos, raw_out)
        files = _postprocess(raw_out, _protos_importing_meshforge(staged, protos))
    _check_versions(files, repo_root / "pyproject.toml")
    return files


# ---------------------------------------------------------------------------
# Compare / write
# ---------------------------------------------------------------------------


def _existing(out_dir: Path) -> dict[str, bytes]:
    if not out_dir.is_dir():
        return {}
    return {
        p.relative_to(out_dir).as_posix(): p.read_bytes()
        for p in sorted(out_dir.rglob("*"))
        if p.is_file() and "__pycache__" not in p.relative_to(out_dir).parts
    }


def _diff(expected: dict[str, bytes], actual: dict[str, bytes]) -> list[str]:
    problems: list[str] = []
    for rel in sorted(expected.keys() | actual.keys()):
        if rel not in actual:
            problems.append(f"missing: {rel}")
        elif rel not in expected:
            problems.append(f"stale (not generated from protos): {rel}")
        elif expected[rel] != actual[rel]:
            problems.append(f"differs: {rel}")
            diff = difflib.unified_diff(
                actual[rel].decode("utf-8", "replace").splitlines(),
                expected[rel].decode("utf-8", "replace").splitlines(),
                f"committed/{rel}",
                f"generated/{rel}",
                lineterm="",
                n=1,
            )
            problems.extend(f"    {line}" for line in list(diff)[:40])
    return problems


def _write(out_dir: Path, files: dict[str, bytes]) -> list[str]:
    changes: list[str] = []
    for rel in _existing(out_dir):
        if rel not in files:
            (out_dir / rel).unlink()
            changes.append(f"removed {rel}")
    for rel, data in files.items():
        target = out_dir / rel
        if target.is_file() and target.read_bytes() == data:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        changes.append(f"wrote {rel}")
    # Drop directories left empty by removals (deepest first).
    for d in sorted((p for p in out_dir.rglob("*") if p.is_dir()), reverse=True):
        if d.name != "__pycache__" and not any(d.iterdir()):
            d.rmdir()
    return changes


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__.split("\n\n")[0] if __doc__ else None
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="regenerate into a temp dir and fail (exit 1) if committed output differs",
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="repository root (default: parent of scripts/)",
    )
    args = parser.parse_args(argv)
    repo_root: Path = args.repo_root.resolve()
    out_dir = repo_root / OUT_DIR

    try:
        files = generate(repo_root)
    except GenError as exc:
        print(f"gen_protos: error: {exc}", file=sys.stderr)
        return EXIT_ERROR

    if args.check:
        problems = _diff(files, _existing(out_dir))
        if problems:
            print(
                f"gen_protos: generated code in {OUT_DIR.as_posix()} is out of date:",
                file=sys.stderr,
            )
            for line in problems:
                print(f"  {line}", file=sys.stderr)
            print("Run: uv run python scripts/gen_protos.py", file=sys.stderr)
            return EXIT_DRIFT
        print(f"gen_protos: {len(files)} generated files up to date")
        return EXIT_OK

    changes = _write(out_dir, files)
    for line in changes:
        print(f"gen_protos: {line}")
    print(f"gen_protos: {len(files)} files, {len(changes)} changed")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
