"""Generate or check the API reference in ``docs/api/`` (V1.0 G5, D414).

    uv run --extra controller --extra agent python scripts/gen_api_docs.py
        regenerate every page in place
    uv run --extra controller --extra agent python scripts/gen_api_docs.py --check
        exit 1 when a committed page differs from the code (CI ``api-docs``)

Every page is derived from the code, never written by hand:

==========================  ===============================================
``rest-controller.md``      the controller's OpenAPI document
                            (``meshforge.controller.http.openapi_document``,
                            the one ``scripts/export_openapi.py`` exports)
``rest-console.md``         the agent's local console API (V0.17 G3)
``grpc.md``                 ``proto/meshforge/v1/*.proto`` compiled by protoc
                            (``apidoc_proto``)
``cli.md``                  ``--help`` of ``compute``, ``meshforge-agent`` and
                            ``meshforge-controller`` (``apidoc_cli``)
``sdk.md``                  the public names of ``meshforge.sdk`` and their
                            docstrings
``README.md``               the index of the pages above
==========================  ===============================================

The output is deterministic (sorted, LF, no clock, no paths): ``--check``
compares byte for byte and also fails on a stray page nobody generates. The
CLI pages need the ``controller`` and ``agent`` extras (the commands import
them for their option types).

Exit codes: 0 written / up to date; 1 drift (``--check``); 2 generation error.
"""

from __future__ import annotations

import argparse
import importlib
import inspect
import os
import sys
from collections.abc import Callable
from pathlib import Path
from typing import Final

_SCRIPTS: Final = Path(__file__).resolve().parent
if str(_SCRIPTS) not in sys.path:
    sys.path.insert(0, str(_SCRIPTS))

import apidoc_cli  # noqa: E402
import apidoc_openapi  # noqa: E402
import apidoc_proto  # noqa: E402

REPO: Final = _SCRIPTS.parent
OUT_DIR: Final = REPO / "docs" / "api"
PROTO_DIR: Final = REPO / "proto"
HEADER: Final = "<!-- Generated by scripts/gen_api_docs.py{src}. DO NOT EDIT. -->"

PROTO_STATUS: Final = {
    "meshforge/v1/agent.proto": "current. The agent <-> controller session (ADR-0002).",
    "meshforge/v1/common.proto": "current. Shared types.",
    "meshforge/v1/enroll.proto": "current. Join-code enrolment (ADR-0016).",
    "meshforge/v1/gpu.proto": (
        "deferred. Mode 2 / Mode 4 skeleton (ADR-0005), not built in v1.0 "
        "(ADR-0012): no process serves GpuService in this release."
    ),
}
"""Release status of each proto file, shown in grpc.md (ADR-0012 deferrals)."""

CLI_TOOLS: Final = (
    (
        "compute",
        "meshforge.cli.app",
        "The user's tool: talks only to the controller's REST API. Output rules, "
        "`--json` and exit codes: [../CLI.md](../CLI.md).",
    ),
    (
        "meshforge-agent",
        "meshforge.agent.main",
        "The worker agent on every laptop (service, join, identity, setup).",
    ),
    (
        "meshforge-controller",
        "meshforge.controller.app",
        "The control plane (service, fabric CA, users, tokens, nodes).",
    ),
)


def _openapi_page(console: bool) -> str:
    if console:
        from meshforge.agent.console.app import openapi_document as console_doc

        return apidoc_openapi.render(
            console_doc(),
            title="Agent console REST reference",
            source="meshforge.agent.console.app.openapi_document()",
        )
    from meshforge.controller.http import openapi_document

    return apidoc_openapi.render(
        openapi_document(),
        title="Controller REST reference",
        source="meshforge.controller.http.openapi_document()",
    )


def grpc_page() -> str:
    files = apidoc_proto.descriptor_set(PROTO_DIR).file
    return apidoc_proto.render(list(files), status=PROTO_STATUS)


def cli_page() -> str:
    # Help text must not depend on the caller's terminal or locale.
    os.environ["NO_COLOR"] = "1"
    os.environ.pop("FORCE_COLOR", None)
    lines = [
        "# Command-line reference",
        "",
        HEADER.format(src=" from each command's --help"),
        "",
        "Every command's own `--help`, at a fixed width. The scripting contract "
        "(stdout/stderr, `--json`, exit codes) is [../CLI.md](../CLI.md).",
        "",
    ]
    for name, module, intro in CLI_TOOLS:
        app = importlib.import_module(module).app
        lines += apidoc_cli.render_tool(name, app, intro)
    return "\n".join(lines).rstrip("\n") + "\n"


def sdk_page() -> str:
    import meshforge.sdk as sdk

    public = sorted(
        n for n in getattr(sdk, "__all__", dir(sdk)) if not n.startswith("_")
    )
    public = [n for n in public if not inspect.ismodule(getattr(sdk, n))]
    lines = [
        "# Python SDK reference (`meshforge.sdk`)",
        "",
        HEADER.format(src=" from meshforge.sdk docstrings"),
        "",
        "```text",
        inspect.cleandoc(sdk.__doc__ or "").rstrip(),
        "```",
        "",
    ]
    if not public:
        lines += [
            "**No public names in this release.** The in-program library "
            "(`remote_gpu()`, `combined_gpu()`, remote tensors) belongs to Mode 2 / "
            "Mode 4, deferred by [ADR-0012](../adr/0012-scope-ship-mode3-complete.md). "
            "Programs use the fabric through the `compute` CLI's `--json` output "
            "([../user/sdk-quickstart.md](../user/sdk-quickstart.md), "
            "[cli.md](cli.md)).",
            "",
        ]
    for name in public:
        obj = getattr(sdk, name)
        try:
            sig = str(inspect.signature(obj))
        except (TypeError, ValueError):
            sig = ""
        lines += [f"## `{name}{sig}`", "", inspect.getdoc(obj) or "(no docstring)", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def index_page() -> str:
    rows = [
        (
            "rest-controller.md",
            "Controller REST API (dashboard, `compute`, scripts)",
            "OpenAPI",
        ),
        ("rest-console.md", "Agent local console API (loopback only)", "OpenAPI"),
        (
            "grpc.md",
            "Agent <-> controller gRPC, enrolment, deferred GPU plane",
            "proto",
        ),
        ("cli.md", "`compute`, `meshforge-agent`, `meshforge-controller`", "--help"),
        ("sdk.md", "`meshforge.sdk` (empty in v1.0; Mode 2/4 deferred)", "docstrings"),
    ]
    lines = [
        "# API reference",
        "",
        HEADER.format(src=""),
        "",
        "Generated from the code by `scripts/gen_api_docs.py`; CI's `api-docs` job "
        "fails when a page is out of date. Regenerate after changing a route, a "
        "`.proto` or a command:",
        "",
        "```bash",
        "uv run --extra controller --extra agent python scripts/gen_api_docs.py",
        "```",
        "",
        "| Page | Covers | Source |",
        "|---|---|---|",
    ]
    lines += [f"| [{page}]({page}) | {what} | {src} |" for page, what, src in rows]
    return "\n".join(lines) + "\n"


PAGES: Final[dict[str, Callable[[], str]]] = {
    "README.md": index_page,
    "rest-controller.md": lambda: _openapi_page(console=False),
    "rest-console.md": lambda: _openapi_page(console=True),
    "grpc.md": grpc_page,
    "cli.md": cli_page,
    "sdk.md": sdk_page,
}


def render_all() -> dict[str, str]:
    """Every page's name -> its text."""
    return {name: build() for name, build in PAGES.items()}


def check(out_dir: Path, pages: dict[str, str]) -> list[str]:
    """The problems ``--check`` reports (empty = up to date)."""
    problems: list[str] = []
    for name, text in pages.items():
        path = out_dir / name
        try:
            current = path.read_bytes().decode("utf-8")
        except OSError:
            problems.append(f"{name}: missing")
            continue
        if current != text:
            problems.append(f"{name}: out of date")
    if out_dir.is_dir():
        problems += [
            f"{p.name}: not generated by this script (remove it)"
            for p in sorted(out_dir.glob("*.md"))
            if p.name not in pages
        ]
    return problems


def write(out_dir: Path, pages: dict[str, str]) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in pages.items():
        (out_dir / name).write_bytes(text.encode("utf-8"))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 on drift")
    parser.add_argument("--out", type=Path, default=OUT_DIR, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        pages = render_all()
    except (ImportError, apidoc_proto.ProtoDocError) as exc:
        print(f"gen_api_docs: {exc}", file=sys.stderr)
        return 2
    if args.check:
        problems = check(args.out, pages)
        for line in problems:
            print(f"gen_api_docs: docs/api/{line}", file=sys.stderr)
        if problems:
            print(
                "gen_api_docs: regenerate with `uv run --extra controller --extra "
                "agent python scripts/gen_api_docs.py`",
                file=sys.stderr,
            )
            return 1
        return 0
    write(args.out, pages)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
